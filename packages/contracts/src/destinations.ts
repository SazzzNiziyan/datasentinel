import { z } from 'zod';

/** Where alerts can go (D-88). GitHub issues and n8n are optional and only
 * usable while their feature flag is on (D-96). */
export const destinationTypes = ['email', 'slack', 'webhook', 'github', 'n8n'] as const;
export type DestinationType = (typeof destinationTypes)[number];

/** The notification kinds the outbox writes (D-86). */
export const notificationKinds = [
  'incident_opened',
  'incident_reopened',
  'incident_assigned',
] as const;
export type NotificationKind = (typeof notificationKinds)[number];

export const DESTINATION_RECIPIENTS_MAX = 10;

/** The delivery kind of a destination test (D-92). It is not an event a
 * destination can subscribe to. */
export const DESTINATION_TEST_KIND = 'destination_test';
/** At most one test per destination in this window. */
export const DESTINATION_TEST_COOLDOWN_MS = 60_000;

const name = z.string().trim().min(1).max(80);
const events = z
  .array(z.enum(notificationKinds))
  .min(1)
  .max(notificationKinds.length)
  .transform((list) => [...new Set(list)]);

/** A Slack incoming-webhook URL: fixed host, https, the documented path. The
 * URL itself is the secret, so it is sealed and never shown again. */
export const SlackWebhookUrl = z
  .string()
  .trim()
  .max(300)
  .regex(
    /^https:\/\/hooks\.slack\.com\/services\/[A-Za-z0-9]+\/[A-Za-z0-9]+\/[A-Za-z0-9]+$/,
    'Use the incoming-webhook URL Slack gave you (https://hooks.slack.com/services/…).',
  );

/** A webhook receiver: https, no credentials, query string, or fragment in
 * the URL (secrets belong in the signature, not the address). The network
 * policy is checked by the API when it is saved and again at delivery
 * (D-88). */
export const WebhookUrl = z
  .string()
  .trim()
  .max(300)
  .regex(
    /^https:\/\/[^\s/?#@\\]+(\/[^\s?#\\]*)?$/,
    'Use an https address without a username, password, or query string.',
  );

/** A GitHub owner or repository name. */
const githubName = z
  .string()
  .trim()
  .min(1)
  .max(100)
  .regex(/^[A-Za-z0-9_.-]+$/, 'Use letters, digits, dots, dashes, and underscores.')
  .refine((v) => v !== '.' && v !== '..', 'Use a real name.');

/** A GitHub access token. Use a fine-grained token limited to one repository
 * with only "Issues: write" (D-96). Sealed on save, never shown again. */
export const GitHubToken = z
  .string()
  .trim()
  .regex(/^(github_pat_|ghp_|gho_|ghs_)[A-Za-z0-9_]{20,255}$/, 'Paste a GitHub access token.');

const githubLabels = z.array(z.string().trim().min(1).max(50)).max(5).default([]);

const recipients = z
  .array(
    z
      .email()
      .max(254)
      .transform((e) => e.toLowerCase()),
  )
  .min(1)
  .max(DESTINATION_RECIPIENTS_MAX)
  .transform((list) => [...new Set(list)]);

/** POST …/destinations. The secret part (Slack URL) is sealed on save; a
 * webhook's signing secret is generated by the server and shown once. */
export const CreateDestinationRequest = z.discriminatedUnion('type', [
  z.strictObject({
    type: z.literal('email'),
    name,
    recipients,
    events: events.default([...notificationKinds]),
  }),
  z.strictObject({
    type: z.literal('slack'),
    name,
    webhookUrl: SlackWebhookUrl,
    events: events.default([...notificationKinds]),
  }),
  z.strictObject({
    type: z.literal('webhook'),
    name,
    url: WebhookUrl,
    events: events.default([...notificationKinds]),
  }),
  z.strictObject({
    type: z.literal('n8n'),
    name,
    url: WebhookUrl,
    events: events.default([...notificationKinds]),
  }),
  // One issue per incident: GitHub destinations only hear about openings.
  z.strictObject({
    type: z.literal('github'),
    name,
    owner: githubName,
    repo: githubName,
    token: GitHubToken,
    labels: githubLabels,
  }),
]);
export type CreateDestinationRequest = z.infer<typeof CreateDestinationRequest>;

/** PATCH …/destinations/{id}: rename, change events or recipients, pause or
 * resume. The type and secrets cannot change here (rotation is separate). */
export const UpdateDestinationRequest = z
  .strictObject({
    name: name.optional(),
    events: events.optional(),
    recipients: recipients.optional(),
    url: WebhookUrl.optional(),
    status: z.enum(['active', 'paused']).optional(),
  })
  .refine((v) => Object.values(v).some((x) => x !== undefined), 'Nothing to change.');
export type UpdateDestinationRequest = z.infer<typeof UpdateDestinationRequest>;

/** Safe to show: no secret, no Slack URL, no signing secret. */
export type DestinationSummary = {
  id: string;
  name: string;
  type: DestinationType;
  status: 'active' | 'paused' | 'archived';
  events: NotificationKind[];
  /** Email recipients; empty for other types. */
  recipients: string[];
  /** Webhook or n8n address; null for other types. */
  url: string | null;
  /** owner/repo for GitHub; null for other types. */
  repository: string | null;
  hasSecret: boolean;
  secretRotatedAt: string | null;
  createdAt: string;
  updatedAt: string;
};

/** Returned once on create for a webhook: the key receivers verify with. */
export type CreatedDestination = DestinationSummary & { signingSecret?: string };

/** POST …/destinations/{id}/test: sends one clearly labelled test message
 * through the real delivery path. `confirm` must be literally true, so a test
 * (which sends data out) is never triggered by accident (D-92). */
export const TestDestinationRequest = z.strictObject({ confirm: z.literal(true) });
export type TestDestinationRequest = z.infer<typeof TestDestinationRequest>;

export type DestinationTestResult = { deliveryId: string; status: 'pending' };

/** A delivery is tried this many times in all (D-93); a failure that can
 * never succeed (a rejected address, a missing secret) stops at once. */
export const DELIVERY_MAX_ATTEMPTS = 5;

const BACKOFF_MS = [60_000, 300_000, 900_000, 3_600_000, 21_600_000];

/** Wait before the next try, given how many tries have failed (1-based):
 * 1 minute, 5, 15, 1 hour, 6 hours. */
export const deliveryBackoffMs = (failedAttempts: number): number =>
  BACKOFF_MS[Math.min(Math.max(failedAttempts, 1), BACKOFF_MS.length) - 1]!;

export type DeliveryStatus = 'pending' | 'sent' | 'failed' | 'suppressed';

/** One row of a destination's delivery history. `lastError` is a short
 * reason code, never provider text. `incidentId` is null for a test. */
export type DeliveryItem = {
  id: string;
  kind: string;
  status: DeliveryStatus;
  attempts: number;
  lastError: string | null;
  /** When the next try is due; meaningful while pending. */
  nextAttemptAt: string;
  incidentId: string | null;
  createdAt: string;
  sentAt: string | null;
};

/** POST …/destinations/{id}/rotate-secret (admin, audited, D-94). A Slack
 * destination takes the new incoming-webhook URL; a webhook destination gets
 * a new signing secret generated by the server and shown once; email has no
 * secret. The old secret stops working at once. */
export const RotateDestinationSecretRequest = z.strictObject({
  webhookUrl: SlackWebhookUrl.optional(),
  token: GitHubToken.optional(),
});
export type RotateDestinationSecretRequest = z.infer<typeof RotateDestinationSecretRequest>;

/** GET …/destinations/options: the types this deployment allows. */
export type DestinationOptions = { types: DestinationType[] };

/** The only fields a notification may carry out of DataSentinel (D-97). No
 * row values, rule results, connection details, or secrets, ever; the
 * database refuses anything else. */
export const NOTIFICATION_PAYLOAD_KEYS = ['title', 'severity', 'datasetName'] as const;

export type NotificationPayload = { title: string; severity: string; datasetName: string };

/** Keeps only the allowed fields, as short strings. Used wherever a payload
 * is copied toward an integration, as a second line of defence. */
export function safeNotificationPayload(input: unknown): Partial<NotificationPayload> {
  const source =
    typeof input === 'object' && input !== null && !Array.isArray(input)
      ? (input as Record<string, unknown>)
      : {};
  const out: Partial<NotificationPayload> = {};
  for (const key of NOTIFICATION_PAYLOAD_KEYS) {
    const value = source[key];
    if (typeof value === 'string') out[key] = value.slice(0, 200);
  }
  return out;
}
